_DATE_SUFFIX_RE = re.compile(r"\s+\d{2}\.\d{2}\.\d{4}\s*-\s*\d{2}\.\d{2}\.\d{4}\s*$")


def _norm(text: str | None) -> str:
    return " ".join((text or "").lower().replace("ё", "е").split())


def _keyword_category(name: str, allowed: set[str] | None = None) -> str | None:
    text = " " + _norm(name) + " "
    for cat, stems in _KEYWORDS:
        if allowed is not None and cat not in allowed:
            continue
        for stem in stems:
            if stem.startswith("="):  # whole word
                pattern = r"(?<![а-яa-z])" + re.escape(stem[1:]) + r"(?![а-яa-z])"
            else:  # word start
                pattern = r"(?<![а-яa-z])" + re.escape(stem)
            if re.search(pattern, text):
                return cat
    return None


def classify(chain: str, chain_category: str | None, name: str, description: str | None = None) -> str:
    cat = _norm(_DATE_SUFFIX_RE.sub("", chain_category or ""))
    text = name if not description else f"{name} {description}"
    if cat:
        for fragment, target in _CHAIN_RULES:
            if fragment in cat:
                if target is None or target == "household_or_nonfood":
                    key = next(k for k in _MIXED_DEFAULTS if k in cat)
                    return _keyword_category(text, _MIXED_ALLOWED[key]) or _MIXED_DEFAULTS[key]
                return target
    return _keyword_category(text) or "other"
