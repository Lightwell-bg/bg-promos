function normKey(s: string): string {
  return s.toLowerCase().replace(/ё/g, "е").trim();
}

export const RU_BG: ReadonlyMap<string, readonly string[]> = new Map(
  ENTRIES.map(([k, v]) => [normKey(k), v] as const),
);

/** Longest multi-word key length, used for phrase matching. */
export const MAX_PHRASE_WORDS = Math.max(...[...RU_BG.keys()].map((k) => k.split(" ").length));

/**
 * Strips Russian case/number endings from words of 4+ letters ("сыра", "мяса", "яиц" lists
 * aside). The stem must keep at least 3 letters so short words like "крем" are not mangled.
 */
function stem(w: string): string {
  if (w.length < 4) return w;
  const s = w.replace(/(ами|ями|ов|ев|ой|ей|ом|ем|ах|ях|ы|и|а|я|у|ю|е|о|ь)$/, "");
  return s.length >= 3 ? s : w;
}

const STEM_INDEX: Map<string, readonly string[]> = (() => {
  const m = new Map<string, readonly string[]>();
  for (const [k, v] of RU_BG) if (!k.includes(" ") && !m.has(stem(k))) m.set(stem(k), v);
  return m;
})();

/** Looks up a (possibly inflected) Russian word or phrase. */
export function lookupRuBg(phrase: string): readonly string[] | undefined {
  const direct = RU_BG.get(phrase);
  if (direct) return direct;
  if (phrase.includes(" ")) return undefined;
  return STEM_INDEX.get(stem(phrase));
}
